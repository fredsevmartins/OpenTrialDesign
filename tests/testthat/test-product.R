test_that("background jobs return exact seeded results and recover from worker errors", {
  skip_if_not_installed("callr")
  p<-trial_project("fixed_simulation",list(n_per_arm=64,nsim=100,seed=42,null=TRUE))
  j<-start_simulation(p);on.exit(cancel_simulation(j),add=TRUE)
  j$process$wait(timeout=30000)
  expect_equal(simulation_status(j)$state,"completed")
  expect_identical(collect_simulation(j)$data,execute_project(p)$data)
  bad<-start_simulation(trial_project("fixed_simulation",list(n_per_arm=1)))
  bad$process$wait(timeout=30000)
  expect_equal(simulation_status(bad)$state,"failed")
  expect_error(collect_simulation(bad),class="otd_job_error")
  expect_equal(simulation_status(j)$state,"completed")
})
