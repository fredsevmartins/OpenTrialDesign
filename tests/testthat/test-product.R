test_that("worker capacity is bounded and released after cancellation", {
  skip_if_not_installed("callr")
  withr::local_options(OpenTrialDesign.max_jobs=1)
  j<-start_simulation(trial_project("fixed_simulation",list(nsim=100000,seed=42)))
  on.exit(cancel_simulation(j),add=TRUE)
  expect_error(start_simulation(trial_project("fixed_simulation")),class="otd_capacity_error")
  cancel_simulation(j)
  k<-start_simulation(trial_project("fixed_simulation",list(nsim=20)))
  on.exit(cancel_simulation(k),add=TRUE)
  k$process$wait(timeout=30000)
  expect_equal(simulation_status(k)$state,"completed")
})
