test_that("JSON projects replay inputs and reject executable or unsupported imports", {
  p<-trial_project("fixed_sample_size",list(effect=.5),"Reproducible trial")
  f<-tempfile();write_project(p,f)
  q<-read_project(f)
  expect_equal(q,p)
  expect_equal(execute_project(q)$data$n_per_arm,64)
  expect_equal(execute_project(q)$project$title,"Reproducible trial")
  expect_error(trial_project("system",list(command="touch /tmp/untrusted")),class="otd_input_error")
  expect_error(trial_project(parameters=list(effect="system('id')")),class="otd_input_error")
  expect_error(trial_project(parameters=list(unrecognized=2)),class="otd_input_error")
  writeLines('{"format":"OpenTrialDesign-project","schema_version":999,"title":"bad","workflow":"fixed_sample_size","parameters":{}}',f)
  expect_error(read_project(f),"schema")
  writeLines("not JSON",f);expect_error(read_project(f),"JSON")
  # Exact numeric fractions and a null optional event target must round-trip.
  p<-trial_project("survival_simulation",list(n_per_arm=50,events=NULL,nsim=20,seed=42))
  write_project(p,f);expect_equal(read_project(f),p)
})
