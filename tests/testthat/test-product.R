test_that("sequential integer enrollment recalibrates native information and power", {
  skip_if_not_installed("rpact")
  for (f in c("none","binding","nonbinding")) {
    x<-sequential_sample_size(futility=f)
    stages<-x$data$stage_plan
    expect_true(all(stages$n_total %% 2 == 0))
    expect_true(all(diff(stages$n_per_arm)>0))
    expect_equal(stages$information,stages$n_per_arm/x$data$n_per_arm)
    expect_gte(x$data$achieved_power,.8-1e-8)
    ref<-rpact::getPowerMeans(x$data$design,alternative=.5,stDev=1,
      normalApproximation=FALSE,maxNumberOfSubjects=x$data$n_total,allocationRatioPlanned=1)
    expect_equal(x$data$achieved_power,as.numeric(ref$overallReject),tolerance=1e-10)
    expect_equal(as.numeric(ref$numberOfSubjects),stages$n_total,tolerance=1e-8)
  }
})
test_that("reproducibility bundles include replay settings and matching checksums", {
  skip_if_not_installed("zip")
  x<-execute_project(trial_project(parameters=list(effect=.5)))
  z<-tempfile(fileext=".zip");export_bundle(x,z,include_report=FALSE)
  folder<-tempfile();dir.create(folder);utils::unzip(z,exdir=folder)
  expect_true(all(c("results.csv","project.json","provenance.txt","manifest.csv") %in% list.files(folder)))
  manifest<-utils::read.csv(file.path(folder,"manifest.csv"))
  expect_identical(unname(tools::md5sum(file.path(folder,manifest$file))),manifest$md5)
  expect_equal(execute_project(read_project(file.path(folder,"project.json")))$data,x$data)
})
