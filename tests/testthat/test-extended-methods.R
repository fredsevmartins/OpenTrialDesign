test_that("non-PH simulation matches native logrank counts and never loses replications", {
  skip_if_not_installed("rpact")
  x<-simulate_nonph(n_total=100,events=40,nsim=20,seed=42)
  raw<-rpact::getData(x$data$native[[2]])
  expect_equal(x$data$summary$rejections[2],sum(raw$rejectPerStage))
  expect_equal(nrow(raw),20)
  expect_equal(x$data$summary$mean_enrolled[2],mean(raw$numberOfSubjects))
  expect_equal(x$data$summary$seed,c(42,43))
  expect_true(all(x$data$summary$target_attainment==1))
  expect_equal(simulate_nonph(n_total=100,events=40,nsim=20,seed=42)$data$summary,x$data$summary)
  expect_error(simulate_nonph(times=c(1,6)),"zero")
  expect_error(simulate_nonph(lambda_control=.06),"one positive")
  expect_error(simulate_nonph(n_total=201),"multiple")
  expect_error(suppressWarnings(simulate_nonph(n_total=40,events=38,dropout=.8,nsim=20,seed=42)),class="otd_simulation_error")
})
