test_that("sparse binary diagnostics are attached and never claim calibration", {
  s<-trial_spec("binary",effect=.005,p_control=.01)
  d<-binary_diagnostics(s,10,TRUE)
  expect_true(d$sparse);expect_equal(d$minimum_expected_count,.1)
  expect_match(d$guidance[1],"not validation")
  x<-trial_power(s,10);expect_true(x$diagnostics$sparse)
  expect_true(diagnose_design(x)$diagnostics$sparse)
  expect_match(paste(capture.output(print(x)),collapse=" "),"Sparse expected counts")
  expect_false(binary_diagnostics(trial_spec("binary",effect=.1,p_control=.3),100)$sparse)
  expect_error(binary_diagnostics(trial_spec(),10),"binary endpoint")
})
test_that("Fisher simulation exactly follows its explicit stats analysis", {
  s<-trial_spec("binary",effect=.1,p_control=.1,alternative="greater")
  x<-simulate_trial(s,10,50,42,TRUE,binary_test="fisher")
  count<-withr::with_seed(42,sum(replicate(50,{
    k<-c(rbinom(1,10,.1),rbinom(1,10,.1))
    fisher.test(cbind(k,10-k),alternative="greater")$p.value<=.05
  })))
  expect_equal(x$data$rejections,count)
  expect_match(x$provenance$method,"Fisher")
  expect_true(x$diagnostics$sparse)
  expect_error(simulate_trial(trial_spec(),10,10,binary_test="fisher"),"binary endpoint")
  p<-trial_project("fixed_simulation",list(endpoint="binary",effect=.1,p_control=.1,n_per_arm=10,nsim=20,binary_test="fisher"))
  f<-tempfile();write_project(p,f);expect_equal(read_project(f),p)
  expect_match(execute_project(p)$provenance$method,"Fisher")
})
test_that("unequal normal NI planning recalculates achieved power at actual integer arms", {
  skip_if_not_installed("rpact")
  for(direction in c("greater","less")){
    x<-means_design(alternative=direction,allocation_ratio=2)
    expect_equal(x$data$n_treatment,2*x$data$n_control)
    expect_gte(x$data$achieved_power,.8-1e-10)
    d<-rpact::getDesignGroupSequential(kMax=1,alpha=.025,beta=.2,sided=1)
    native<-rpact::getPowerMeans(d,alternative=0,thetaH0=if(direction=="greater")-.3 else .3,
      stDev=1,normalApproximation=FALSE,maxNumberOfSubjects=x$data$n_total,allocationRatioPlanned=2,directionUpper=direction=="greater")
    expect_equal(x$data$rejection_probability,as.numeric(native$overallReject),tolerance=1e-10)
  }
  expect_error(means_design(effect=-.4),"alternative side")
  expect_error(means_design(alternative="two.sided"),"one-sided")
  expect_error(means_design(n_control=10),"both")
  boundary<-means_design(effect=-.3,n_control=100,n_treatment=200)
  expect_true(is.na(boundary$data$achieved_power))
  expect_equal(boundary$data$rejection_probability,.025,tolerance=1e-6)
})
