test_that("equivalence exact power uses both asymmetric margins and realized allocation", {
  skip_if_not_installed("PowerTOST")
  x<-means_design(hypothesis="equivalence",effect=.02,lower=-.2,upper=.4,allocation_ratio=2)
  expect_gte(x$data$achieved_power,.8-1e-10)
  reference<-PowerTOST::power.TOST(alpha=.025,logscale=FALSE,theta0=.02,theta1=-.2,theta2=.4,CV=1,
    n=c(x$data$n_treatment,x$data$n_control),design="parallel",method="exact")
  expect_equal(x$data$achieved_power,reference,tolerance=1e-10)
  previous<-PowerTOST::power.TOST(alpha=.025,logscale=FALSE,theta0=.02,theta1=-.2,theta2=.4,CV=1,
    n=c(2*(x$data$n_control-1),x$data$n_control-1),design="parallel",method="exact")
  expect_lt(previous,.8)
  expect_error(means_design(hypothesis="equivalence",effect=.5),"inside")
  expect_error(means_design(hypothesis="equivalence",alternative="less"),"both|one-sided")
})
