# Run from the repository root. Dependencies stay in an isolated project library.
if(getRversion()<"4.5.0")stop("OpenTrialDesign requires R >= 4.5.0")
source("scripts/product-library.R")
library<-activate_product_library(create=TRUE)
if(!nzchar(Sys.getenv("RENV_PATHS_ROOT")))
  Sys.setenv(RENV_PATHS_ROOT=file.path(tools::R_user_dir("OpenTrialDesign","cache"),"renv"))
if(!requireNamespace("renv",quietly=TRUE))
  install.packages("renv",lib=library,repos="https://cloud.r-project.org")
renv::consent(provided=TRUE)
renv::restore(lockfile="renv.lock",library=library,prompt=FALSE)
status<-system2(file.path(R.home("bin"),"R"),c("CMD","build","."))
if(status!=0)stop("Package build failed")
status<-system2(file.path(R.home("bin"),"R"),c("CMD","INSTALL","--install-tests","-l",shQuote(library),"OpenTrialDesign_0.3.0.tar.gz"))
if(status!=0)stop("Package installation failed")
cat("Installed in ",library,"\nStart: Rscript scripts/start-product.R\n",sep="")
