from playwright.sync_api import sync_playwright
from pathlib import Path
import os,json,csv,zipfile,hashlib
root=Path(__file__).resolve().parents[1];out=root/'validation';checks=[]
def record(label): checks.append({'workflow':label,'passed':True})
with sync_playwright() as p:
 b=p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH') or None,headless=True,args=['--no-sandbox'])
 page=b.new_page(viewport={'width':1440,'height':1100});errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(os.environ.get('OTD_APP_URL','http://127.0.0.1:3840/'),wait_until='networkidle')
 page.wait_for_function('window.Shiny && Shiny.shinyapp && Shiny.shinyapp.$socket.readyState === 1')
 page.locator('#calculate').click();page.get_by_role('tab',name='Sample size and power',exact=True).click()
 page.wait_for_function("document.querySelector('#fixed').textContent.includes('64')")
 record('fixed planning and achieved power')
 page.locator('#alpha').fill('1');page.locator('#calculate').click()
 page.wait_for_function("document.querySelector('#fixed').textContent.includes('strictly between')")
 page.locator('#alpha').fill('0.05');page.locator('#calculate').click()
 page.wait_for_function("document.querySelector('#fixed').textContent.includes('64')")
 record('invalid scientific input and recovery without session disconnect')
 page.get_by_role('tab',name='Group sequential designs',exact=True).click();page.locator('#sequential').click();page.locator('#seqsample').click()
 page.wait_for_function("document.querySelector('#seqsample_result').textContent.includes('130')")
 record('integer sequential enrollment and recalibrated boundaries')
 page.get_by_role('tab',name='Projects and exports',exact=True).click()
 with page.expect_download() as info: page.locator('#project').click()
 jf=out/'product-project.json';info.value.save_as(str(jf));project=json.loads(jf.read_text())
 assert project['parameters']['alpha']==.05 and project['parameters']['effect']==.5
 record('download frozen JSON project')
 with page.expect_download() as info: page.locator('#bundle').click()
 zf=out/'product-bundle.zip';info.value.save_as(str(zf))
 with zipfile.ZipFile(zf) as z:
  assert {'project.json','results.csv','manifest.csv','provenance.txt'} <= set(z.namelist())
  for row in csv.DictReader(z.read('manifest.csv').decode().splitlines()):assert hashlib.md5(z.read(row['file'])).hexdigest()==row['md5']
 record('download reproducibility ZIP and verify file integrity')
 page.locator('#project_file').set_input_files(str(jf));page.locator('#runproject').click()
 page.evaluate("document.querySelector('#report_source').selectize.setValue('imported')")
 page.wait_for_function("document.querySelector('#snapshot').textContent.includes('Fixed trial sample size')")
 with page.expect_download() as info:page.locator('#csv').click()
 cf=out/'product-replayed.csv';info.value.save_as(str(cf));assert 'n_per_arm' in cf.read_text() and '64' in cf.read_text()
 record('import and replay a saved project with matching CSV')
 bad=out/'invalid-project.json';bad.write_text('{"workflow":"system"}')
 page.locator('#project_file').set_input_files(str(bad))
 page.wait_for_function("document.querySelector('#import_preview').textContent.includes('schema')")
 page.locator('#project_file').set_input_files(str(jf));page.locator('#runproject').click()
 record('reject unsupported project and recover')
 page.locator('#nsim').fill('100000');page.get_by_role('tab',name='Monte Carlo simulation',exact=True).click();page.locator('#simulate').click()
 page.wait_for_function("document.querySelector('#job_status').textContent.includes('Running')")
 page.get_by_role('tab',name='Design configuration',exact=True).click()
 page.locator('#cancel').click();page.wait_for_function("document.querySelector('#job_status').textContent.includes('cancelled')")
 record('responsive navigation during simulation and cancellation')
 page.locator('#nsim').fill('20');page.get_by_role('tab',name='Monte Carlo simulation',exact=True).click();page.locator('#simulate').click()
 page.wait_for_function("document.querySelector('#job_status').textContent.includes('Completed')")
 page.wait_for_function("document.querySelector('#simulation_result').textContent.includes('Monte Carlo')")
 record('successful background run after cancellation')
 page.get_by_role('tab',name='Adaptive designs',exact=True).click();page.locator('#adaptive').click()
 page.wait_for_function("document.querySelector('#adaptive_result').textContent.includes('equality null')")
 record('adaptive background simulation')
 page.get_by_role('tab',name='Survival studies',exact=True).click();page.locator('#n').fill('50');page.locator('#events').fill('40');page.locator('#survsim').click()
 page.wait_for_function("document.querySelector('#survsim_result').textContent.includes('target_attainment')")
 record('event-driven survival background simulation')
 page.get_by_role('tab',name='Scientific reporting',exact=True).click()
 with page.expect_download() as info:page.locator('#report').click()
 hf=out/'product-report.html';info.value.save_as(str(hf));assert 'Methodological provenance' in hf.read_text()
 record('methodological HTML report')
 if os.environ.get('OTD_TEST_PDF')=='1':
  page.evaluate("document.querySelector('#report_format').selectize.setValue('pdf')")
  with page.expect_download(timeout=60000) as info:page.locator('#report').click()
