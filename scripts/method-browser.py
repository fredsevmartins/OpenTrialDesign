"""Real browser acceptance for sparse counts and verified method extensions."""
from pathlib import Path
import os,json,csv
from playwright.sync_api import sync_playwright
out=Path(__file__).resolve().parents[1]/'validation';checks=[];audits=[]
def record(name):checks.append({'workflow':name,'passed':True})
with sync_playwright() as p:
 b=p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH') or None,headless=True,args=['--no-sandbox'])
 page=b.new_page(viewport={'width':1440,'height':1100});errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(os.environ.get('OTD_APP_URL','http://127.0.0.1:3850/'),wait_until='networkidle')
 page.wait_for_function('window.Shiny && Shiny.shinyapp && Shiny.shinyapp.$socket.readyState===1')
 page.add_script_tag(path=os.environ['AXE_CORE_PATH'])
 def audit(name):
  report=page.evaluate("async()=>await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}})")
  audits.append({'state':name,'violations':report['violations'],'incomplete':report['incomplete']})
  assert not report['violations'],json.dumps(report['violations'])
 page.locator('#endpoint').select_option('binary');page.locator('#effect').fill('0.005');page.locator('#pcontrol').fill('0.01');page.locator('#n').fill('10');page.locator('#seed').click()
 page.wait_for_function("document.querySelector('#binary-approximation-guidance')?.textContent.includes('Sparse binary counts')")
 assert 'do not repair miscalibration' in page.locator('#binary-approximation-guidance').inner_text()
 with page.expect_download() as info:page.locator('#binary_calibration').click()
 f=out/'binary-calibration-browser.csv';info.value.save_as(str(f));rows=list(csv.DictReader(f.read_text().splitlines()))
 assert len(rows)==10 and sum(r['within_screen']=='FALSE' for r in rows)==6
 record('visible sparse-count warning and downloadable historical calibration evidence')
 audit('sparse binary warning')
 page.locator('#nsim').fill('20');page.get_by_role('tab',name='Monte Carlo simulation',exact=True).click();page.locator('#binary_test').select_option('fisher');page.locator('#simulate').click()
 page.wait_for_function("document.querySelector('#simulation_result')?.textContent.includes('Fisher exact')")
 assert 'sample size' in page.locator('#scientific-contract').inner_text()
 record('explicit Fisher simulation without relabelling approximate sample sizing')
 page.get_by_role('tab',name='Margins and allocation',exact=True).click();page.locator('#mean_calculate').click()
 page.wait_for_function("document.querySelector('#mean_result')?.textContent.includes('rpact')")
 assert 'n_treatment' in page.locator('#mean_result').inner_text()
 page.locator('#mean_direction').select_option('less');page.locator('#mean_calculate').click()
 page.wait_for_function("document.querySelector('#mean_result')?.textContent.includes('native rpact')")
 page.wait_for_function("document.querySelector('#scientific-contract')?.textContent.includes('effect >= 0.3')")
 record('unequal-allocation noninferiority in both directions with explicit null margin')
 page.locator('#mean_hypothesis').select_option('equivalence');page.locator('#mean_calculate').click()
 page.wait_for_function("document.querySelector('#mean_result')?.textContent.includes('PowerTOST')")
 assert 'not 2*alpha' in page.locator('#scientific-contract').inner_text()
 audit('equivalence margins and alpha')
 record('exact TOST sizing and component-alpha scientific review')
 page.locator('#mean_simulate').click()
 page.wait_for_function("document.querySelector('#mean_mc_result')?.textContent.includes('upper boundary null')")
 record('background equivalence simulation evaluates both null boundaries')
 page.get_by_role('tab',name='Projects and exports',exact=True).click();page.locator('#report_source').select_option('means')
 with page.expect_download() as info:page.locator('#project').click()
 f=out/'equivalence-browser-project.json';info.value.save_as(str(f));saved=json.loads(f.read_text())
 assert saved['workflow']=='means_design' and saved['parameters']['hypothesis']=='equivalence' and saved['parameters']['allocation_ratio']==2
 page.locator('#project_file').set_input_files(str(f));page.locator('#runproject').click();page.locator('#report_source').select_option('imported')
 page.wait_for_function("document.querySelector('#snapshot')?.textContent.includes('equivalence')")
 record('portable equivalence project export and replay')
 page.get_by_role('tab',name='Non-PH survival',exact=True).click();page.locator('#nph_n').fill('100');page.locator('#nph_events').fill('40');page.locator('#nph_treatment').fill('0.08,0.03');page.locator('#nph_simulate').click()
 page.wait_for_function("document.querySelector('#nph_result')?.textContent.includes('alternative profile')")
 assert 'no constant HR estimand' in page.locator('#scientific-contract').inner_text()
 audit('crossing hazard profile')
 record('native non-PH logrank simulation with crossing hazards and equal-curve null')
 page.locator('#nph_events').fill('101');page.locator('#nph_simulate').click()
 page.wait_for_function("document.querySelector('#job_status')?.textContent.includes('events must be less')")
 page.locator('#nph_events').fill('40');page.locator('#nph_simulate').click()
 page.wait_for_function("document.querySelector('#job_status')?.textContent.includes('Completed')")
 record('invalid event target fails and recovers without disconnected session')
 page.set_viewport_size({'width':390,'height':844});assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
 page.screenshot(path=str(out/'method-mobile.png'),full_page=True);record('mobile method interface without page overflow')
 assert not errors,errors
 b.close()
(out/'method-browser.json').write_text(json.dumps({'checks':checks,'javascript_errors':errors},indent=2)+'\n')
(out/'method-accessibility.json').write_text(json.dumps({'axe_version':'4.10.3','states':audits},indent=2)+'\n')
print(json.dumps(checks))
